import React from 'react';
import {renderToString} from 'react-dom/server';
import assert from 'node:assert/strict';
import ClubNews,{ClubNewsDirectory} from '../src/app/club-news';
import NewsHub from '../src/app/news-hub';
const club={id:'palmeiras',name:'Palmeiras',image:'https://example.test/escudo.png'};
const cards=[{id:'a',club_id:'palmeiras',club_post:true,status:'Publicado',title:'Nossa primeira notícia',created_at:'2026-10-15'},{id:'b',club_id:'palmeiras',club_post:true,status:'Rascunho',title:'Rascunho privado',created_at:'2026-10-15'},{id:'c',club_id:'santos',club_post:true,status:'Publicado',title:'Outro clube',created_at:'2026-10-15'}];
const Card=({n}:any)=><h2>{n.title}</h2>,Content=({text}:any)=><p>{text}</p>;
const raw=renderToString(<ClubNews club={club} d={{news:cards,user:null}} reload={()=>{}} Card={Card} Content={Content}/>);
const html=raw.replace(/<!--.*?-->/g,'');
assert.ok(html.includes('Notícias do Palmeiras'));assert.ok(html.includes('Nossa primeira notícia'));assert.ok(!html.includes('Rascunho privado'));assert.ok(!html.includes('Outro clube'));assert.ok(!html.includes('Gerenciar notícias do clube'));assert.ok(html.includes('Entrar para publicar'));
const directory=renderToString(<ClubNewsDirectory clubs={[club]}/>);assert.ok(directory.includes('/clubes/palmeiras/noticias'));assert.ok(directory.includes('Escudo Palmeiras'));
console.log('Notícias dos clubes: página, links e proteção de rascunhos na renderização pública conferidos.');

const league={id:'liga',club_id:'palmeiras',club_post:false,status:'Publicado',title:'Informe oficial da competição',summary:'Comunicado',created_at:'2026-10-15'};
const items=[...cards,league];
const leagueHtml=renderToString(<NewsHub d={{news:items,user:null}} clubs={[club]} kind="league"/>);
const clubHtml=renderToString(<NewsHub d={{news:items,user:null}} clubs={[club]} kind="clubs"/>);
assert.ok(leagueHtml.includes(league.title));assert.ok(!leagueHtml.includes(cards[0].title));
assert.ok(clubHtml.includes(cards[0].title));assert.ok(!clubHtml.includes(league.title));assert.ok(!clubHtml.includes(cards[1].title));
assert.ok(clubHtml.includes('Filtrar notícias por clube'));assert.ok(clubHtml.includes('/noticias/clubes'));
const ownPage=renderToString(<ClubNews club={club} d={{news:items,user:null}} reload={()=>{}} Card={Card} Content={Content}/>);
assert.ok(!ownPage.includes(league.title));
console.log('Centrais da liga e dos clubes: matérias separadas, filtros e rascunhos conferidos.');
